"""Usage: python3 lms2py.py examples/NAME.lms > py/NAME.py

Translate the _dsl_ block of an lmblender example into a bpy script using lmb_bpy."""
import re, sys, pathlib
src = pathlib.Path(sys.argv[1]).read_text()
m = re.search(r'_dsl_[^;]*;(.*?)end _dsl_', src, re.S)
body = m.group(1)
out = []
for line in body.splitlines():
    # split on ; and // only outside string literals
    parts, cur, q, comment, i = [], '', False, '', 0
    while i < len(line):
        ch = line[i]
        if ch == '"': q = not q
        if not q and line.startswith('//', i): comment = line[i+2:]; break
        if not q and ch == ';': parts.append(cur); cur = ''
        else: cur += ch
        i += 1
    parts.append(cur)
    stmts = [s.strip() for s in parts if s.strip()]
    for s in stmts:
        s = re.sub(r'^let\s+', '', s)
        s = re.sub(r'\btrue\b', 'True', s); s = re.sub(r'\bfalse\b', 'False', s)
        if re.match(r'scene\.render_', s): s = s.replace('"build/', '"blender/')
        out.append(s)
    if comment.strip():
        out.append('# ' + comment.strip())
name = pathlib.Path(sys.argv[1]).stem
print('# SPDX-FileCopyrightText: 2025-2026 lmblender contributors\n# SPDX-License-Identifier: MIT')
print(f'# Blender/bpy port of examples/{name}.lms (generated by docs/tutorial/blender/lms2py.py, reviewed by hand)')
print('import os, sys\nsys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))\nimport lmb_bpy\n\nscene = lmb_bpy.Scene()')
print('\n'.join(out))
print('lmb_bpy.done()')
